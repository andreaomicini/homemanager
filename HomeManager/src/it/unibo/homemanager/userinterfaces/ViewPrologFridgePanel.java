	    private void btAddToListButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btAddToListButtonActionPerformed
	        String nameProduct = this.productNameText.getText().trim();
	        int quantity = 0;
	        try {
	            quantity = Integer.parseInt(this.quantityProductText.getText());
	        } catch (Exception e) {
	            JOptionPane.showMessageDialog(null,
	                    "Value to quantity non Integer;\nPlease insert value to Integer in quantity area.",
	                    "INCORRECT VALUE ", JOptionPane.ERROR_MESSAGE);
	            return;
	        }
	        if (quantity <= 0) {
	            JOptionPane.showMessageDialog(null,
	                    "Incorrect value. Please insert value > 0.",
	                    "ACTION INVALID", JOptionPane.ERROR_MESSAGE);
	            return;
	        }

	        int choice = JOptionPane.showConfirmDialog(null,
	                "Do you really want to insert " + nameProduct + "?",
	                "INSERT CHECK", JOptionPane.OK_CANCEL_OPTION);
	        if (choice == JOptionPane.OK_OPTION) {
	            this.tcsonAgent.insert(nameProduct, quantity);
	            this.quantityProductText.setText("");
	            this.productNameText.setText("");
	            fillList();
	            return;
	        } else {
	            JOptionPane.showMessageDialog(null,
	                    "Product not added,try Again.",
	                    "ACTION NOT SUCCEEDE", JOptionPane.ERROR_MESSAGE);
	            return;
	        }
	    }//GEN-LAST:event_btAddToListButtonActionPerformed

	    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
	        Ingredient element_selected;
	        int quantity = 0;
	        try {
	            element_selected = listProduct.getSelectedValue();
	        } catch (Exception e) {
	            JOptionPane.showMessageDialog(null,
	                    "No product selected.Please select a product\n from those listed on the left.",
	                    "ACTION INVALID", JOptionPane.ERROR_MESSAGE);
	            return;
	        }
	        
	        int quantity_actual =element_selected.getQuantity();
	        try {
	            quantity = Integer.parseInt(this.quantityToDeleteTextField.getText());
	        } catch (Exception e) {
	            JOptionPane.showMessageDialog(null,
	                    "Value to quantity non Integer;\nPlease insert value to Integer in quantity area.",
	                    "INCORRECT VALUE ", JOptionPane.ERROR_MESSAGE);
	            return;
	        }
	        int quantity_total = quantity_actual - quantity;
	        if (quantity <= 0 || quantity_total < 0) {
	            JOptionPane.showMessageDialog(null,
	                    "Incorrect value. Enter value greater than 0 and less than the current value.",
	                    "ACTION INVALID", JOptionPane.ERROR_MESSAGE);
	            return;
	        }
	        int choice = JOptionPane.showConfirmDialog(null,
	                "Do you really want to delete " + element_selected.getName() + "?",
	                "DELETE CHECK", JOptionPane.OK_CANCEL_OPTION);
	        if (choice == JOptionPane.OK_OPTION) {
	            this.tcsonAgent.updateFridgeContent(element_selected.getName(), quantity_total);
	            this.quantityToDeleteTextField.setText("");
	            fillList();
	            return;
	        } else {
	            JOptionPane.showMessageDialog(null,
	                    "Product not deleted,try again.",
	                    "ACTION NOT SUCCEEDED", JOptionPane.ERROR_MESSAGE);
	            return;
	        }

	    }//GEN-LAST:event_jButton2ActionPerformed

