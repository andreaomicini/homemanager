    private void showButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_showButtonActionPerformed
        String[] nameAndId = this.listAgentComboBox.getSelectedItem().toString().split(" ");
        String name = nameAndId[0];
        TucsonAgentInterface t = tucsonManageDevice.getAgentbyName(name);
        if(t!=null)
            this.mp.loadAgentPanel(t,user);
                
    }//GEN-LAST:event_showButtonActionPerformed

    private void listAgentComboBoxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_listAgentComboBoxActionPerformed
        if(listAgentComboBox.getItemCount() == tucsonManageDevice.getListStringDevice().size()) {
            String[] nameAndId = this.listAgentComboBox.getSelectedItem().toString().split(" ");
            String name = nameAndId[0];
            TucsonAgentInterface t = tucsonManageDevice.getAgentbyName(name);
            if (t == null) {
                this.showButton.setEnabled(false);
            } else {
                this.showButton.setEnabled(true);
            }
        }
    }//GEN-LAST:event_listAgentComboBoxActionPerformed

